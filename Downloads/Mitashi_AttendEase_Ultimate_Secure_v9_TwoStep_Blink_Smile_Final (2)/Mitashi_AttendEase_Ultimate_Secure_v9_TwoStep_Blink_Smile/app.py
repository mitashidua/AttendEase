@app.post("/api/kiosk/<session_id>/liveness/challenge")
@firebase_required
@teacher_required
def kiosk_liveness_challenge_api(session_id: str):
    tid = current_teacher()["teacher_id"]
    item = _teacher_session(session_id)
    if not item or not cloud.session_active(item):
        return jsonify({"ok": False, "session_closed": True, "message": "Attendance is closed."}), 400
    challenge_id = secrets.token_urlsafe(18)
    rng = secrets.SystemRandom()
    # Two-step challenge using only blink and smile. Each attempt contains
    # exactly one blink step and one smile step in a fresh cryptographically
    # randomized order. The server keeps the full sequence private and reveals
    # only the current action after the previous one passes.
    actions = ["blink", "smile"]
    rng.shuffle(actions)
    with _LIVENESS_LOCK:
        _LIVENESS_CHALLENGES[challenge_id] = {
            "teacher_id": tid,
            "session_id": session_id,
            "class_id": item["class_id"],
            "created_mono": time.monotonic(),
            "actions": actions,
            "index": 0,
            "baseline": None,
            "passed": False,
            "used": False,
            "verify_attempts": 0,
        }
    return jsonify({
        "ok": True,
        "challenge_id": challenge_id,
        "first_action": actions[0],
        "total_steps": len(actions),
        "expires_in": int(_LIVENESS_TTL),
    })


@app.post("/api/kiosk/<session_id>/liveness/baseline")
@firebase_required
@teacher_required
def kiosk_liveness_baseline_api(session_id: str):
    tid = current_teacher()["teacher_id"]
    data = request.get_json(silent=True) or {}
    challenge_id = str(data.get("challenge_id", ""))
    frames = data.get("frames") or []
    item = _liveness_record(challenge_id, tid, session_id)
    if not item:
        return jsonify({"ok": False, "message": "Liveness challenge expired. Start again."}), 400
    if len(frames) < 4:
        return jsonify({"ok": False, "message": "Keep your face centered for calibration."}), 400
    try:
        baseline = liveness_baseline([decode_data_url(x) for x in frames[:8]])
        with _LIVENESS_LOCK:
            item["baseline"] = baseline
        return jsonify({"ok": True, "usable": int(baseline.get("usable", 0))})
    except Exception as exc:
        return jsonify({"ok": False, "message": str(exc)}), 400


@app.post("/api/kiosk/<session_id>/liveness/step")
@firebase_required
@teacher_required
def kiosk_liveness_step_api(session_id: str):
    tid = current_teacher()["teacher_id"]
    data = request.get_json(silent=True) or {}
    challenge_id = str(data.get("challenge_id", ""))
    action = str(data.get("action", ""))
    frames = data.get("frames") or []
    item = _liveness_record(challenge_id, tid, session_id)
    if not item:
        return jsonify({"ok": False, "message": "Liveness challenge expired. Start again."}), 400
    if item.get("used"):
        return jsonify({"ok": False, "message": "This liveness challenge was already used."}), 400
    if item.get("passed"):
        return jsonify({"ok": True, "passed": True, "complete": True, "next_index": len(item.get("actions", []))})
    if not item.get("baseline"):
        return jsonify({"ok": False, "message": "Neutral face calibration is required first."}), 400
    index = int(item.get("index", 0))
    actions = item.get("actions") or []
    if index >= len(actions):
        return jsonify({"ok": False, "message": "Invalid liveness state."}), 400
    expected = actions[index]
    if action != expected:
        return jsonify({"ok": False, "message": "Liveness action is out of sequence."}), 400
    if len(frames) < 5:
        return jsonify({"ok": False, "message": "Not enough camera frames for this action."}), 400
    try:
        passed, message, diagnostics = verify_liveness_action(
            action, [decode_data_url(x) for x in frames[:18]], item["baseline"]
        )
        if passed:
            with _LIVENESS_LOCK:
                item["index"] = index + 1
                complete = item["index"] >= len(actions)
                if complete:
                    item["passed"] = True
                    item["passed_mono"] = time.monotonic()
            next_action = None if complete else actions[index + 1]
            return jsonify({
                "ok": True, "passed": True, "complete": complete,
                "next_index": index + 1, "next_action": next_action,
                "message": message, "diagnostics": diagnostics,
            })
        return jsonify({"ok": True, "passed": False, "complete": False, "message": message, "diagnostics": diagnostics})
    except Exception as exc:
        return jsonify({"ok": False, "message": str(exc)}), 400


@app.post("/api/kiosk/<session_id>/verify")
@firebase_required
@teacher_required
def kiosk_verify_api(session_id: str):
    tid = current_teacher()["teacher_id"]
    item = _teacher_session(session_id)
    if not item or not cloud.session_active(item):
        return jsonify({"ok": False, "session_closed": True, "message": "Attendance is closed."}), 400
    class_id = item["class_id"]
    students = cloud.list_students(tid, class_id)
    allowed = {s["student_id"].upper() for s in students if s.get("face_enrolled")}
    if not allowed:
        return jsonify({"ok": False, "message": "No enrolled face profiles are available for this class."}), 400

    data = request.get_json(silent=True) or {}
    liveness_token = str(data.get("liveness_token", ""))
    live = _liveness_record(liveness_token, tid, session_id)
    if not live or not live.get("passed") or live.get("used"):
        return jsonify({"ok": False, "liveness_required": True, "message": "Complete the random liveness challenge before face recognition."}), 403
    # Keep the passed liveness token alive for at most two immediate identity
    # captures. This avoids forcing the student through the full liveness
    # sequence again just because one final frame burst was blurred/off-center.
    # The token is still short-lived and is consumed on success or after two
    # identity attempts.
    with _LIVENESS_LOCK:
        attempts = int(live.get("verify_attempts", 0)) + 1
        live["verify_attempts"] = attempts
        if attempts > 2:
            live["used"] = True
            return jsonify({"ok": False, "liveness_required": True, "message": "Identity retry limit reached. Start a new liveness challenge."}), 403
    frames = data.get("frames") or []
    if len(frames) < 4:
        return jsonify({"ok": False, "message": "Face verification needs several camera frames."}), 400
    try:
        cache_key = f"{tid}:{class_id}"
        version = cloud.class_model_version(tid, class_id)
        cached = get_cached_model(cache_key, version)
        if cached:
            recognizer, label_map = cached
        else:
            samples = cloud.download_class_faces(tid, class_id)
            recognizer, label_map = build_or_get_model(cache_key, version, samples)
        raw_frames = [decode_data_url(frame) for frame in frames[:10]]
        student_id, face_distance, usable, matching = identify_frames(
            raw_frames, recognizer, label_map, allowed_student_ids=allowed, threshold=75.0
        )
        if not student_id:
            with _LIVENESS_LOCK:
                retry_allowed = int(live.get("verify_attempts", 0)) < 2
                if not retry_allowed:
                    live["used"] = True
            message = "Face match was unclear. Return to the center, look straight at the camera, and keep still."
            if not retry_allowed:
                message += " Start secure verification again."
            return jsonify({
                "ok": False, "retry_identity": retry_allowed, "message": message,
                "usable_frames": usable, "matching_frames": matching,
                "best_distance": None if face_distance >= 998 else round(float(face_distance), 2),
            }), 403
        try:
            record = cloud.mark_attendance(tid, class_id, session_id, student_id, face_distance, liveness_actions=live.get("actions", []))
        except ValueError as exc:
            if "already marked" in str(exc).lower():
                student = cloud.get_student(tid, class_id, student_id) or {"name": student_id}
                with _LIVENESS_LOCK:
                    live["used"] = True
                return jsonify({"ok": False, "already": True, "message": f"{student.get('name')} ({student_id}) is already marked present.", "student": student}), 409
            raise
        with _LIVENESS_LOCK:
            live["used"] = True
        return jsonify({"ok": True, "message": "Identity verified. Attendance marked in Firebase.", "student": {"name": record["student_name"], "student_id": student_id}, "record": record, "matching_frames": matching})
    except Exception as exc:
        return jsonify({"ok": False, "message": str(exc)}), 400


