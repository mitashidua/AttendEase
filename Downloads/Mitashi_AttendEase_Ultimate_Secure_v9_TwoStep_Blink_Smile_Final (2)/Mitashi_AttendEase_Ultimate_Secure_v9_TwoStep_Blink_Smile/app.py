@app.route("/setup/firebase", methods=["GET", "POST"])
def firebase_setup():
    if request.method == "POST":
        file = request.files.get("service_account")
        database_url = request.form.get("database_url", "")
        if not file or not file.filename:
            flash("Select the Firebase service-account JSON file.", "error")
        else:
            try:
                cloud.save_configuration(database_url, file.read())
                flash("Firebase Realtime Database connected successfully.", "success")
                return redirect(url_for("login"))
            except Exception as exc:
                flash(f"Firebase setup failed: {exc}", "error")
    return render_template("firebase_setup.html")


@app.route("/login", methods=["GET", "POST"])
@firebase_required
def login():
    if current_teacher():
        return redirect(url_for("teacher_dashboard"))
    if request.method == "POST":
        try:
            teacher = cloud.authenticate_teacher(request.form.get("email", ""), request.form.get("password", ""))
        except Exception as exc:
            flash(f"Firebase error: {exc}", "error")
            teacher = None
        if teacher:
            session.clear()
            session["teacher_id"] = teacher["teacher_id"]
            return redirect(url_for("teacher_dashboard"))
        flash("Invalid teacher email or password.", "error")
    return render_template("login.html")


