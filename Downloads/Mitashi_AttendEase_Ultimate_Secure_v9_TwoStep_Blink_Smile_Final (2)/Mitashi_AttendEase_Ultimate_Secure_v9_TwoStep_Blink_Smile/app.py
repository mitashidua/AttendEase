def firebase_ready() -> bool:
    return cloud.app is not None


def current_teacher():
    tid = session.get("teacher_id")
    if not tid or not firebase_ready():
        return None
    try:
        return cloud.get_teacher(tid)
    except Exception:
        return None


def firebase_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if not firebase_ready():
            return redirect(url_for("firebase_setup"))
        return fn(*args, **kwargs)
    return wrapper


def teacher_required(fn):
    @wraps(fn)
    def wrapper(*args, **kwargs):
        if not current_teacher():
            return redirect(url_for("login"))
        return fn(*args, **kwargs)
    return wrapper


