# In-memory, short-lived challenge state. Challenges are generated by the server,
# expire quickly, are tied to one teacher/session, and are single-use.
_LIVENESS_CHALLENGES = {}
_LIVENESS_LOCK = threading.RLock()
_LIVENESS_TTL = 150.0


def _cleanup_liveness():
    now = time.monotonic()
    with _LIVENESS_LOCK:
        stale = [key for key, value in _LIVENESS_CHALLENGES.items() if now - value.get("created_mono", now) > 120.0]
        for key in stale:
            _LIVENESS_CHALLENGES.pop(key, None)


def _liveness_record(challenge_id: str, teacher_id: str, session_id: str):
    _cleanup_liveness()
    with _LIVENESS_LOCK:
        item = _LIVENESS_CHALLENGES.get(challenge_id)
        if not item:
            return None
        if item.get("teacher_id") != teacher_id or item.get("session_id") != session_id:
            return None
        if time.monotonic() - item.get("created_mono", 0.0) > _LIVENESS_TTL:
            _LIVENESS_CHALLENGES.pop(challenge_id, None)
            return None
        return item


IST = timezone(timedelta(hours=5, minutes=30))


def format_ist(value):
    """Convert an ISO timestamp stored in UTC to Indian Standard Time for display."""
    if not value:
        return "-"
    try:
        dt = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        return dt.astimezone(IST).strftime("%d-%m-%Y %I:%M:%S %p")
    except (ValueError, TypeError):
        return str(value)


app.jinja_env.filters["ist_time"] = format_ist


